SELECT '========== 示例：用户及其主治医生 ==========' AS 信息;
SELECT u.health_id AS 健康ID, u.name AS 姓名, p.name AS 主治医生, p.specialty AS 专科
FROM User u
LEFT JOIN Provider p ON u.primary_provider_id = p.provider_id
LIMIT 5;

SELECT '========== 示例：本月预约 ==========' AS 信息;
SELECT u.name AS 用户, p.name AS 医生, 
       DATE_FORMAT(a.appointment_date, '%Y-%m-%d %H:%i') AS 预约时间,
       a.consultation_type AS 类型, a.status AS 状态
FROM Appointment a
JOIN User u ON a.user_id = u.user_id
JOIN Provider p ON a.provider_id = p.provider_id
WHERE MONTH(a.appointment_date) = MONTH(CURDATE())
ORDER BY a.appointment_date
LIMIT 5;

SELECT '========== 示例：健康挑战参与情况 ==========' AS 信息;
SELECT c.challenge_name AS 挑战名称, c.challenge_type AS 类型,
       COUNT(p.user_id) AS 参与人数,
       ROUND(AVG(p.current_progress), 1) AS 平均进度
FROM Challenge c
LEFT JOIN Participation p ON c.challenge_id = p.challenge_id
GROUP BY c.challenge_id, c.challenge_name, c.challenge_type
ORDER BY 参与人数 DESC
LIMIT 5;

